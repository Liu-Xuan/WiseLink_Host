import { adaptTdmsDailySource } from '../../../server/modules/tdms-source/tdms-daily-source-adapter';
import { prepareTdmsDailySourceImport } from '../../../server/modules/tdms-source/tdms-daily-metadata-contract';
import {
  isReviewedEfRequestUnknownFieldCaption,
  validateReviewedCompleteTabRoster,
  validateReviewedEfRequestModifiedMirrors,
} from '../../../server/modules/tdms-source/tdms-reviewed-complete-source-types';
import { classifyOwnFieldReference } from '../../../server/modules/tdms-source/tdms-own-reference-models';
import { TdmsSourceService } from '../../../server/modules/tdms-source/tdms-source.service';
import { HostDecisionTdmsSourceAuthorization } from '../../../server/modules/tdms-source/tdms-source.authorization';
import { MemoryTdmsRepository, nativeScope } from './tdms-memory-double';
import { actor } from './tdms-fixtures';
import {
  copyComplete,
  sealComplete,
  syntheticCompleteEnvelope,
} from './tdms-complete-owned.fixture';
import {
  efRequestGolden,
  efRequestProof,
  efRequestStructuralRosters,
  resealEfRequest,
  syntheticEfRequest,
  type EfRequestEnvelope,
} from './tdms-efrequest-contract.fixture';

const validate = (env: EfRequestEnvelope) => prepareTdmsDailySourceImport(env);
function edit(env: EfRequestEnvelope, fn: (read: any) => void) {
  for (const read of efRequestProof(env).reads) {
    fn(read);
    efRequestStructuralRosters(read);
  }
  return resealEfRequest(env);
}
const opinion = (read: any) =>
  read.fields.find((f: any) => f.value.actualLabel === 'Assessment Opinion:');
const unknown = (read: any) =>
  read.fields.find((f: any) => f.value.actualLabel === '');

describe('EFRequest exact current C1 wire and C2 non-promotion boundary (synthetic only)', () => {
  it('agrees with expectations generated by supplied SHA-qualified pure helpers', () => {
    const g = efRequestGolden;
    expect(
      validateReviewedCompleteTabRoster({
        scopeId: g.scopeId,
        owner: g.owner,
        rosterEvidence: g.rosterEvidence,
        contentTabIds: g.contentTabIds,
      }),
    ).toBe(g.expected.rosterWithPair);
    expect(
      validateReviewedCompleteTabRoster({
        scopeId: g.scopeId,
        owner: g.owner,
        rosterEvidence: { tabIds: g.contentTabIds },
        contentTabIds: g.contentTabIds,
      }),
    ).toBe(g.expected.rosterBothAbsent);
    expect(
      isReviewedEfRequestUnknownFieldCaption({
        scopeId: g.scopeId,
        owner: g.owner,
        field: g.unknown,
      }),
    ).toBe(g.expected.unknownCaption);
    expect(
      validateReviewedEfRequestModifiedMirrors({
        scopeId: g.scopeId,
        owner: g.owner,
        fields: g.mirrors,
      }),
    ).toEqual(g.expected.modifiedMirrors);
    for (const r of g.referenceModels)
      expect(
        classifyOwnFieldReference({
          scopeId: g.scopeId,
          fieldActualLabel: r.label,
          targetRef: r.ref,
        }),
      ).toEqual(r.model);
  });

  it.each([true, false])(
    'preserves the exact pair=%s roster, source header version and unchanged old absent shape',
    (pair) => {
      const env = syntheticEfRequest({ pair });
      const before = JSON.stringify(env);
      const result = validate(env);
      expect(result.envelope).toEqual(env);
      expect(JSON.stringify(env)).toBe(before);
      const native = adaptTdmsDailySource(env).output.nativePackage.records[0];
      expect(native.sourceVersion).toEqual({
        rawRevision: 'A',
        rawIteration: '1',
        confirmation: 'SOURCE_DECLARED',
      });
      expect(
        (native.rawFields.completeOwnedSource as any).reads[1].rosterEvidence,
      ).toEqual(efRequestProof(env).reads[1].rosterEvidence);
      expect(native.coverage.status).toBe('PARTIAL');
      if (!pair)
        expect(
          (native.rawFields.completeOwnedSource as any).reads[1].rosterEvidence,
        ).not.toHaveProperty('nonContentControls');
    },
  );

  it('keeps legacy non-EF absent roster and the EF absent-pair eight-state observation', () => {
    for (const scope of [
      'SB_PROCESSING_FORM',
      'ENGINEERING_ASSESSMENT',
    ] as const) {
      const env = syntheticCompleteEnvelope(scope);
      expect(validate(env).envelope).toEqual(env);
      expect(efRequestProof(env).reads[1].rosterEvidence).not.toHaveProperty(
        'nativeTabStripIds',
      );
    }
  });

  it.each([
    'one-half',
    'extra-key',
    'business-caption',
    'wrong-model',
    'wrong-tag',
    'wrong-root',
    'duplicate-action',
    'omitted-business-tab',
    'reordered-content',
    'action-in-content',
  ])('rejects roster/control tampering: %s', (change) => {
    const env = edit(syntheticEfRequest(), (r) => {
      const e = r.rosterEvidence,
        c = e.nonContentControls[0];
      if (change === 'one-half') delete e.nonContentControls;
      if (change === 'extra-key') c.callerReviewed = true;
      if (change === 'business-caption') c.rawCaption = 'Business content';
      if (change === 'wrong-model') c.modelRevision += '-other';
      if (change === 'wrong-tag') c.tag = 'BUTTON';
      if (change === 'wrong-root') c.rootLocator = '#caller-root';
      if (change === 'duplicate-action') e.nativeTabStripIds.push(c.actionId);
      if (change === 'omitted-business-tab') e.nativeTabStripIds.splice(1, 1);
      if (change === 'reordered-content')
        [e.nativeTabStripIds[0], e.nativeTabStripIds[1]] = [
          e.nativeTabStripIds[1],
          e.nativeTabStripIds[0],
        ];
      if (change === 'action-in-content') e.tabIds.push(c.actionId);
    });
    expect(() => validate(env)).toThrow(
      'TDMS_REVIEWED_COMPLETE_TAB_ROSTER_INVALID',
    );
  });

  it('retains the empty source-native caption as exact unknown NOT_READ evidence', () => {
    const env = syntheticEfRequest({ unknownCaption: true });
    const native = adaptTdmsDailySource(env).output.nativePackage.records[0];
    expect(
      native.content.completeOwnedFields!.find(
        (f) => f.value.actualLabel === '',
      ),
    ).toEqual(efRequestGolden.unknown);
    expect(native.coverage.gaps).toContain('OWN_CONTENT_UNREAD');
    expect(native.coverage.gaps).toContain('COMPLETION_CERTIFICATE_NOT_ISSUED');
    expect(native.coverage.status).toBe('PARTIAL');
  });

  it.each([
    'blank',
    'value',
    'wrong-section',
    'wrong-tag',
    'profile-inferred-label',
    'wrong-locator',
    'linked-unknown',
  ])(
    'rejects empty caption outside its exact NOT_READ context: %s',
    (change) => {
      const env = edit(syntheticEfRequest({ unknownCaption: true }), (r) => {
        const f = unknown(r);
        if (change === 'blank')
          Object.assign(f.value, {
            state: 'BLANK',
            rawValue: '',
            observedTotalCodepoints: 0,
          });
        if (change === 'value')
          Object.assign(f.value, {
            state: 'VALUE',
            rawValue: 'Invented',
            observedTotalCodepoints: 8,
          });
        if (change === 'wrong-section')
          f.sectionId = efRequestGolden.contentTabIds[0] + '::General';
        if (change === 'wrong-tag') f.nativeControl.tag = 'INPUT';
        if (change === 'profile-inferred-label')
          f.labelOrigin = 'PROFILE_EXPECTED';
        if (change === 'wrong-locator') f.value.locator = '#unrelated unknown';
        if (change === 'linked-unknown')
          f.links = [
            {
              rawHref: '/infoPage?oid=OR:wt.doc.WTDocument:241099',
              targetRef: 'OR:wt.doc.WTDocument:241099',
              numberRaw: 'SYNTHETIC',
              nativeRole: 'RELATED',
              locator: f.fieldId + ' a',
            },
          ];
      });
      expect(() => validate(env)).toThrow('TDMS_COMPLETE_OWN_STRING_INVALID');
    },
  );

  it.each(['removed-blocker', 'claimed-readable-tab'])(
    'rejects an unacknowledged unknown caption: %s',
    (change) => {
      const env = edit(syntheticEfRequest({ unknownCaption: true }), (r) => {
        if (change === 'removed-blocker')
          r.rosterEvidence.unknownRequiredSurfaces = [];
        else r.tabs[0].state = 'VALUE';
      });
      expect(() => validate(env)).toThrow(
        'TDMS_COMPLETE_OWN_UNKNOWN_CAPTION_UNACKNOWLEDGED',
      );
    },
  );

  it('rejects a malformed unknown-surface acknowledgement as a bounded DTO error', () => {
    const env = edit(syntheticEfRequest({ unknownCaption: true }), (r) => {
      r.rosterEvidence.unknownRequiredSurfaces = { sourceClaim: 'unknown' };
    });
    try {
      validate(env);
      throw new Error('Malformed acknowledgement was accepted');
    } catch (reason) {
      expect(reason).toMatchObject({
        code: 'TDMS_COMPLETE_OWN_UNKNOWN_CAPTION_UNACKNOWLEDGED',
        statusCode: 400,
      });
    }
  });

  it('does not drop an unknown occurrence from one read or its typed projection', () => {
    const env = syntheticEfRequest({ unknownCaption: true });
    efRequestProof(env).reads[0].fields = efRequestProof(
      env,
    ).reads[0].fields.filter((f: any) => f.value.actualLabel !== '');
    resealEfRequest(env);
    expect(() => validate(env)).toThrow(
      'TDMS_COMPLETE_OWN_OBSERVATION_CHANGED',
    );
    const typed = syntheticEfRequest({ unknownCaption: true });
    typed.package.records[0].content.completeOwnedFields =
      typed.package.records[0].content.completeOwnedFields!.filter(
        (f) => f.value.actualLabel !== '',
      );
    sealComplete(typed);
    expect(() => validate(typed)).toThrow('TDMS_COMPLETE_OWN_RECORD_INVALID');
  });

  it.each([
    'wrong-header-slot',
    'four-header-slots',
    'field-header-conflict',
    'caller-type-proof',
    'changed-own-type',
    'cross-owner',
  ])('rejects native owner/header/version tampering: %s', (change) => {
    const env = edit(syntheticEfRequest(), (r) => {
      if (change === 'wrong-header-slot')
        r.owner.rawHeaderIdentifier =
          r.owner.number + ', A.1, Not the technical version';
      if (change === 'four-header-slots')
        r.owner.rawHeaderIdentifier += ', A.1';
      if (change === 'field-header-conflict')
        Object.assign(r.owner.technicalVersionFieldEvidence, {
          state: 'VALUE',
          rawValue: 'A.2',
          observedTotalCodepoints: 3,
        });
      if (change === 'caller-type-proof') r.owner.reviewedEFRequest = true;
      if (change === 'changed-own-type') {
        r.owner.nativeTypeEvidence.rawValue =
          'WCTYPE|wt.doc.WTDocument|com.airchina.Other';
        r.owner.nativeTypeEvidence.observedTotalCodepoints = [
          ...r.owner.nativeTypeEvidence.rawValue,
        ].length;
      }
      if (change === 'cross-owner')
        r.owner.sourceRecordId = 'OR:wt.doc.WTDocument:241099';
    });
    expect(() => validate(env)).toThrow(
      /TDMS_COMPLETE_OWN_(?:OWNER|VERSION|TYPE|FIELDS)_/,
    );
  });

  it.each([
    'missing-mirror',
    'wrong-section',
    'wrong-locator',
    'modified-drift',
    'both-unread',
    'unread-tab-claimed-value',
  ])('rejects mirror omissions/drift/unread inconsistencies: %s', (change) => {
    const env = edit(syntheticEfRequest(), (r) => {
      const mirrors = r.fields.filter(
        (f: any) => f.value.actualLabel === 'Last Modified:',
      );
      if (change === 'missing-mirror')
        r.fields = r.fields.filter((f: any) => f !== mirrors[1]);
      if (change === 'wrong-section')
        mirrors[0].sectionId = mirrors[1].sectionId;
      if (change === 'wrong-locator')
        mirrors[0].value.locator = '#different-modified';
      if (change === 'modified-drift')
        mirrors[1].value.rawValue = '2026-10-14 08:00';
      if (change === 'both-unread')
        for (const f of mirrors)
          Object.assign(f.value, {
            state: 'NOT_READ',
            rawValue: null,
            observedTotalCodepoints: 0,
          });
      if (change === 'unread-tab-claimed-value')
        Object.assign(mirrors[1].value, {
          state: 'NOT_READ',
          rawValue: null,
          observedTotalCodepoints: 0,
        });
    });
    expect(() => validate(env)).toThrow(/TDMS_COMPLETE_OWN_MODIFIED_MIRROR_/);
  });

  it('retains a single unread mirror as PARTIAL only when its native tab remains NOT_READ', () => {
    const env = edit(syntheticEfRequest(), (r) => {
      const f = r.fields.find(
        (f: any) =>
          f.sectionId.endsWith('::MoreAttributesGroup') &&
          f.value.actualLabel === 'Last Modified:',
      );
      Object.assign(f.value, {
        state: 'NOT_READ',
        rawValue: null,
        observedTotalCodepoints: 0,
      });
      r.tabs[0].state = 'NOT_READ';
    });
    expect(validate(env).envelope).toEqual(env);
    expect(env.package.coverage.gaps).toContain('OWN_CONTENT_UNREAD');
  });

  it('retains raw User/Context/Location references and native roles without collecting bodies or adding edges', async () => {
    const env = syntheticEfRequest({ references: true });
    const prepared = adaptTdmsDailySource(env);
    expect(prepared.output.nativePackage.relations).toEqual([]);
    const occurrences = efRequestProof(env).targetOccurrences;
    expect(
      occurrences.filter(
        (o: any) => o.relationshipRole === 'OUT_OF_SCOPE_REFERENCE',
      ),
    ).toHaveLength(6);
    expect(occurrences.at(-1).relationshipRole).toBe('UNKNOWN');
    const repository = new MemoryTdmsRepository();
    const claims = copyComplete(prepared.memberClaims);
    const authority = new HostDecisionTdmsSourceAuthorization(
      async () => [{ scope: nativeScope, permissionRevision: 'synthetic-1' }],
      async ({ grant }) => ({
        ...grant,
        authorityRef: 'synthetic-import',
        captureRetentionAllowed: true,
        nativeProjectionAllowed: true,
        permittedMembers: claims,
      }),
      async ({ grant }) => ({
        ...grant,
        authorityRef: 'synthetic-read',
        retainedCaptureReadAllowed: true,
        permittedMembers: claims,
      }),
    );
    const artifacts = { acquire: jest.fn() };
    const service = new TdmsSourceService(repository, authority, artifacts, {
      assertRead: jest.fn(),
    });
    const receipt = await service.importDailyMetadata(actor(), env);
    expect(Object.keys(receipt)).toHaveLength(10);
    expect(receipt).toMatchObject({
      artifactCount: 0,
      relationCount: 0,
      objectCount: 1,
    });
    expect(
      (await service.readDailyMetadataImport(actor(), env.requestId)).package,
    ).toEqual(env.package);
    expect(
      repository.state.revisions[0].record.content.completeOwnedFields,
    ).toEqual(env.package.records[0].content.completeOwnedFields);
    expect(artifacts.acquire).not.toHaveBeenCalled();
  });

  it('rejects spoofed raw role or outside-reference endpoint identity', () => {
    const env = syntheticEfRequest({ references: true });
    efRequestProof(env).targetOccurrences[0].relationshipRole =
      'CURRENT_CONTENT';
    resealEfRequest(env);
    expect(() => validate(env)).toThrow('TDMS_COMPLETE_OWN_RECORD_INVALID');
    const other = syntheticEfRequest({ references: true });
    efRequestProof(other).targetOccurrences[4].rawHref += '&caller=changed';
    resealEfRequest(other);
    expect(() => validate(other)).toThrow('TDMS_COMPLETE_OWN_RECORD_INVALID');
    expect(
      classifyOwnFieldReference({
        scopeId: 'EO',
        fieldActualLabel: 'Location:',
        targetRef: 'OR:wt.folder.Cabinet:241014',
      }).relationshipRole,
    ).toBe('UNKNOWN');
  });

  it.each(['Approved', '已批准'])(
    'rejects %s native opinion literals outside the exact Estimated policy',
    (state) => {
      expect(() =>
        adaptTdmsDailySource(syntheticEfRequest({ state })),
      ).toThrow('TDMS_OPINION_STATE_NOT_ELIGIBLE');
    },
  );

  it.each(['Estimated'])(
    'keeps eligible %s native opinion literals without adopting them as approved Host opinions',
    (state) => {
      const native = adaptTdmsDailySource(syntheticEfRequest({ state })).output
        .nativePackage.records[0];
      expect(
        native.content.completeOwnedFields!.find(
          (f) => f.value.actualLabel === 'Assessment Opinion:',
        )!.value.state,
      ).toBe('VALUE');
      expect(native.content).not.toHaveProperty('opinions');
      expect(native.coverage.gaps).toContain(
        'COMPLETION_CERTIFICATE_NOT_ISSUED',
      );
    },
  );

  it.each(['Estimating', 'Draft', 'Rejected'])(
    'retains noneligible %s policy-gated NOT_APPLICABLE/null/zero and rejects its invented body',
    (state) => {
      const env = syntheticEfRequest({ state });
      expect(validate(env).envelope).toEqual(env);
      expect(opinion(efRequestProof(env).reads[1]).value).toMatchObject({
        state: 'NOT_APPLICABLE',
        rawValue: null,
        observedTotalCodepoints: 0,
      });
      edit(env, (r) =>
        Object.assign(opinion(r).value, {
          state: 'VALUE',
          rawValue: 'Fake',
          observedTotalCodepoints: 4,
        }),
      );
      expect(() => validate(env)).toThrow(
        state === 'Estimating'
          ? 'TDMS_ESTIMATING_STATE_ONLY_REQUIRED'
          : 'TDMS_OPINION_STATE_NOT_ELIGIBLE',
      );
    },
  );

  it('never promotes missing opinion, other NOT_APPLICABLE or genuine unread observations to C2 completeness', () => {
    const env = edit(syntheticEfRequest(), (r) => {
      r.fields = r.fields.filter(
        (f: any) => f.value.actualLabel !== 'Assessment Opinion:',
      );
      // Leave both required mirrors intact; add an unrelated native NAP literal.
      r.fields.push({
        ...copyComplete(r.fields[0]),
        fieldId: '#synthetic-extra other',
        tabId: r.tabs[1].tabId,
        sectionId: r.sections[2].sectionId,
        value: {
          state: 'NOT_APPLICABLE',
          actualLabel: 'Other:',
          rawValue: null,
          locator: '#synthetic-extra other',
          observedTotalCodepoints: 0,
        },
        links: [],
      });
    });
    expect(validate(env).envelope.package.coverage.status).toBe('PARTIAL');
    const native = adaptTdmsDailySource(env).output.nativePackage.records[0];
    expect(native.coverage.gaps).toContain('COMPLETION_CERTIFICATE_NOT_ISSUED');
    for (const change of ['scopeComplete', 'COMPLETE'] as const) {
      const forged = copyComplete(env);
      if (change === 'scopeComplete') forged.package.query.scopeComplete = true;
      else forged.package.coverage.status = 'COMPLETE';
      sealComplete(forged);
      expect(() => validate(forged)).toThrow(
        change === 'scopeComplete'
          ? 'COMPLETE_OWN_PACKAGE_LIMITS_REQUIRED'
          : 'TDMS_DAILY_COMPLETE_COVERAGE_UNPROVEN',
      );
    }
  });
});
